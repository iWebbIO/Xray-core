const WRITE_CHUNK: usize = 16 * 1024;
const ACCEPT_QUEUE: usize = 64;
// Larger than one stream window, while remaining a fixed connection memory
// bound: one unread tunnel must not immediately consume every stream's budget.
const CONNECTION_WINDOW: u32 = 1024 * 1024;
const HANDSHAKE_TIMEOUT: Duration = Duration::from_secs(30);

fn invalid(error: impl std::fmt::Display) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidData, error.to_string())
}

fn h2_error(error: h2::Error) -> io::Error {
    let kind = if let Some(error) = error.get_io() {
        error.kind()
    } else if error.reason() == Some(h2::Reason::CANCEL) {
        io::ErrorKind::Interrupted
    } else {
        io::ErrorKind::ConnectionAborted
    };
    io::Error::new(kind, error)
}

fn validate_client(config: &Config) -> io::Result<()> {
    if config.mode() != Mode::StreamOne {
        return Err(io::Error::new(
            io::ErrorKind::Unsupported,
            "HTTP/2 XHTTP client implements explicit stream-one only",
        ));
    }
    let authority: http::uri::Authority = config.host.parse().map_err(invalid)?;
    if authority.host().is_empty() || config.host.contains('@') {
        return Err(invalid("HTTP/2 XHTTP client requires a valid authority"));
    }
    Ok(())
}

/// Strip only HTTP/1 hop-by-hop fields and framing. All XHTTP camouflage,
/// cookies, padding, and CORS values are generated by the shared parent helpers.
fn h2_headers(headers: &[httparse::Header<'_>], maximum: usize) -> io::Result<HeaderMap> {
    let mut connection_tokens = HashSet::new();
    for header in headers {
        if header.name.eq_ignore_ascii_case("connection") {
            for token in std::str::from_utf8(header.value)
                .map_err(invalid)?
                .split(',')
            {
                connection_tokens.insert(token.trim().to_ascii_lowercase());
            }
        }
    }
    let mut result = HeaderMap::new();
    let mut length = 0usize;
    for header in headers {
        let name = header.name.to_ascii_lowercase();
        if matches!(
            name.as_str(),
            "connection"
                | "keep-alive"
                | "proxy-connection"
                | "transfer-encoding"
                | "upgrade"
                | "host"
                | "content-length"
        ) || connection_tokens.contains(&name)
        {
            continue;
        }
        if name == "te" && !header.value.eq_ignore_ascii_case(b"trailers") {
            continue;
        }
        length = length.saturating_add(name.len() + header.value.len() + 32);
        if length > maximum {
            return Err(invalid("XHTTP HTTP/2 header list exceeds configured limit"));
        }
        result.append(
            HeaderName::from_bytes(name.as_bytes()).map_err(invalid)?,
            HeaderValue::from_bytes(header.value).map_err(invalid)?,
        );
    }
    Ok(result)
}

fn header_slots(wire: &[u8], maximum: usize) -> io::Result<usize> {
    if wire.len() > maximum {
        return Err(invalid(
            "XHTTP HTTP header template exceeds configured limit",
        ));
    }
    // Every line needs at least CRLF, so this remains bounded by the byte limit.
    let count = wire.windows(2).filter(|bytes| *bytes == b"\r\n").count();
    Ok(count)
}

fn request(config: &Config) -> io::Result<Request<()>> {
    let wire = config.stream_request("")?;
    let mut slots = vec![httparse::EMPTY_HEADER; header_slots(&wire, config.max_header)?];
    let mut parsed = httparse::Request::new(&mut slots);
    if parsed.parse(&wire).map_err(invalid)? != httparse::Status::Complete(wire.len()) {
        return Err(invalid("incomplete XHTTP request header template"));
    }
    let uri = Uri::builder()
        .scheme(config.scheme.as_str())
        .authority(config.host.as_str())
        .path_and_query(
            parsed
                .path
                .ok_or_else(|| invalid("missing XHTTP request path"))?,
        )
        .build()
        .map_err(invalid)?;
    let mut request = Request::builder()
        .method(
            Method::from_bytes(
                parsed
                    .method
                    .ok_or_else(|| invalid("missing XHTTP method"))?
                    .as_bytes(),
            )
            .map_err(invalid)?,
        )
        .version(Version::HTTP_2)
        .uri(uri)
        .body(())
        .map_err(invalid)?;
    *request.headers_mut() = h2_headers(parsed.headers, config.max_header)?;
    Ok(request)
}

fn response(
    config: &Config,
    request: &Head,
    status: u16,
    streaming: bool,
) -> io::Result<Response<()>> {
    let wire = config.response(request, status, streaming);
    let mut slots = vec![httparse::EMPTY_HEADER; header_slots(&wire, config.max_header)?];
    let mut parsed = httparse::Response::new(&mut slots);
    if parsed.parse(&wire).map_err(invalid)? != httparse::Status::Complete(wire.len()) {
        return Err(invalid("incomplete XHTTP response header template"));
    }
    let mut response = Response::builder()
        .status(status)
        .version(Version::HTTP_2)
        .body(())
        .map_err(invalid)?;
    *response.headers_mut() = h2_headers(parsed.headers, config.max_header)?;
    Ok(response)
}

fn request_head(request: &Request<RecvStream>, maximum: usize) -> io::Result<Head> {
    let target = request
        .uri()
        .path_and_query()
        .map(ToString::to_string)
        .unwrap_or_else(|| "/".into());
    let mut length = target.len() + request.method().as_str().len();
    let mut headers = Vec::new();
    for (name, value) in request.headers() {
        length = length.saturating_add(name.as_str().len() + value.as_bytes().len() + 32);
        if length > maximum {
            return Err(invalid(
                "XHTTP HTTP/2 request headers exceed configured limit",
            ));
        }
        headers.push((
            name.to_string(),
            std::str::from_utf8(value.as_bytes())
                .map_err(invalid)?
                .to_owned(),
        ));
    }
    // :authority is the canonical HTTP/2 host; do not let a second Host field
    // override it. A missing authority retains any ordinary Host fallback.
    if let Some(authority) = request.uri().authority() {
        headers.retain(|(name, _)| !name.eq_ignore_ascii_case("host"));
        headers.push(("Host".into(), authority.to_string()));
    }
    Ok(Head {
        method: request.method().to_string(),
        target,
        status: 0,
        headers,
    })
}

struct Driver(JoinHandle<()>);
impl Drop for Driver {
    fn drop(&mut self) {
        self.0.abort();
    }
}

/// One reusable HTTP/2 connection. This is connection reuse, not Xray's Xmux
/// balancing, lifetime, request-count, or retry policy.
#[derive(Clone)]
pub struct Client {
    sender: h2::client::SendRequest<Bytes>,
    config: Arc<Config>,
    driver: Arc<Driver>,
}

impl Client {
    pub async fn handshake(io: BoxStream, config: Config) -> io::Result<Self> {
        validate_client(&config)?;
        let mut builder = h2::client::Builder::new();
        builder
            .max_header_list_size(config.max_header as u32)
            .initial_connection_window_size(CONNECTION_WINDOW)
            .max_send_buffer_size(WRITE_CHUNK * 2);
        let (sender, connection) = tokio::time::timeout(HANDSHAKE_TIMEOUT, builder.handshake(io))
            .await
            .map_err(|_| {
                io::Error::new(
                    io::ErrorKind::TimedOut,
                    "XHTTP HTTP/2 client handshake timed out",
                )
            })?
            .map_err(h2_error)?;
        let driver = Arc::new(Driver(tokio::spawn(async move {
            if let Err(error) = connection.await {
                tracing::debug!(%error, "XHTTP HTTP/2 client connection ended");
            }
        })));
        Ok(Self {
            sender,
            config: Arc::new(config),
            driver,
        })
    }

    /// Return after queuing request headers, before receiving response headers.
    /// The peer is allowed to wait for application DATA before responding.
    pub async fn open(&self) -> io::Result<Tunnel> {
        let mut sender = self.sender.clone().ready().await.map_err(h2_error)?;
        let (response, send) = sender
            .send_request(request(&self.config)?, false)
            .map_err(h2_error)?;
        Ok(Tunnel::new(
            Role::Client,
            send,
            None,
            Some(response),
            Some(self.driver.clone()),
        ))
    }
}

/// Fresh physical connection convenience adapter, matching the parent Connector
/// shape. The returned Tunnel owns the driver's lifetime after Client is dropped.
pub async fn connect(config: Config, connector: Connector) -> io::Result<BoxStream> {
    validate_client(&config)?;
    let client = Client::handshake(connector().await?, config).await?;
    Ok(client.open().await?.boxed())
}

/// Drives one physical HTTP/2 connection and yields every accepted logical
/// stream-one tunnel. A bounded queue never stalls the underlying H2 driver.
pub struct Server {
    incoming: mpsc::Receiver<io::Result<Tunnel>>,
    driver: Arc<Driver>,
}

impl Server {
    pub async fn handshake(io: BoxStream, config: Config) -> io::Result<Self> {
        if !config.mode.allows_stream_one() {
            return Err(io::Error::new(
                io::ErrorKind::Unsupported,
                "XHTTP HTTP/2 server implements stream-one only",
            ));
        }
        let mut builder = h2::server::Builder::new();
        builder
            .max_header_list_size(config.max_header as u32)
            .initial_connection_window_size(CONNECTION_WINDOW)
            .max_concurrent_streams(ACCEPT_QUEUE as u32)
            .max_send_buffer_size(WRITE_CHUNK * 2);
        let mut connection =
            tokio::time::timeout(HANDSHAKE_TIMEOUT, builder.handshake::<_, Bytes>(io))
                .await
                .map_err(|_| {
                    io::Error::new(
                        io::ErrorKind::TimedOut,
                        "XHTTP HTTP/2 server handshake timed out",
                    )
                })?
                .map_err(h2_error)?;
        let (sender, incoming) = mpsc::channel(ACCEPT_QUEUE);
        let driver = Arc::new(Driver(tokio::spawn(async move {
            let mut closing = false;
            loop {
                let next = tokio::select! {
                    _ = sender.closed(), if !closing => {
                        closing = true;
                        connection.graceful_shutdown();
                        continue;
                    }
                    next = connection.accept() => next,
                };
                let Some(next) = next else {
                    break;
                };
                let (request, response) = match next {
                    Ok(next) => next,
                    Err(error) => {
                        let _ = sender.try_send(Err(h2_error(error)));
                        break;
                    }
                };
                match accept_request(request, response, &config) {
                    Ok(Some(tunnel)) => {
                        // A failed try_send drops and cancels only the excess
                        // stream; it cannot suspend other streams' I/O.
                        let _ = sender.try_send(Ok(tunnel));
                    }
                    Ok(None) => {}
                    Err(error) => tracing::debug!(%error, "XHTTP HTTP/2 request rejected"),
                }
            }
        })));
        Ok(Self { incoming, driver })
    }

    pub async fn accept(&mut self) -> io::Result<Option<Tunnel>> {
        match self.incoming.recv().await {
            Some(Ok(mut tunnel)) => {
                tunnel.driver = Some(self.driver.clone());
                Ok(Some(tunnel))
            }
            Some(Err(error)) => Err(error),
            None => Ok(None),
        }
    }
}

fn accept_request(
    request: Request<RecvStream>,
    mut responder: h2::server::SendResponse<Bytes>,
    config: &Config,
) -> io::Result<Option<Tunnel>> {
    let head = request_head(&request, config.max_header)?;
    let metadata = config.metadata(&head);
    let status = if (!config.host.is_empty() && !super::valid_host(head.get("Host"), &config.host))
        || metadata.is_err()
    {
        404
    } else if head.method == "OPTIONS" {
        200
    } else if !config.valid_padding(&head) {
        400
    } else if metadata
        .as_ref()
        .is_ok_and(|(session, _)| !session.is_empty())
    {
        400
    } else {
        200
    };
    if status != 200 || head.method == "OPTIONS" {
        responder
            .send_response(response(config, &head, status, false)?, true)
            .map_err(h2_error)?;
        return Ok(None);
    }
    let send = responder
        .send_response(response(config, &head, 200, true)?, false)
        .map_err(h2_error)?;
    Ok(Some(Tunnel::new(
        Role::Server,
        send,
        Some(request.into_body()),
        None,
        None,
    )))
}

#[derive(Clone, Copy, Eq, PartialEq)]
enum Role {
    Client,
    Server,
}

/// Direct raw HTTP/2 body adapter. At most one received DATA frame is retained;
/// receive capacity is released only as bytes are copied to the application.
/// Writes reserve capacity before copying at most 16 KiB into the H2 sender.
pub struct Tunnel {
    role: Role,
    send: SendStream<Bytes>,
    recv: Option<RecvStream>,
    response: Option<ResponseFuture>,
    received: Bytes,
    read_closed: bool,
    write_closed: bool,
    data_ended: bool,
    terminal_error: Option<(io::ErrorKind, String)>,
    driver: Option<Arc<Driver>>,
}

impl Tunnel {
    fn new(
        role: Role,
        send: SendStream<Bytes>,
        recv: Option<RecvStream>,
        response: Option<ResponseFuture>,
        driver: Option<Arc<Driver>>,
    ) -> Self {
        Self {
            role,
            send,
            recv,
            response,
            received: Bytes::new(),
            read_closed: false,
            write_closed: false,
            data_ended: false,
            terminal_error: None,
            driver,
        }
    }

    pub fn boxed(self) -> BoxStream {
        Box::new(self)
    }

    fn poll_read_inner(
        &mut self,
        cx: &mut Context<'_>,
        buf: &mut ReadBuf<'_>,
    ) -> Poll<io::Result<()>> {
        if let Some((kind, message)) = &self.terminal_error {
            return Poll::Ready(Err(io::Error::new(*kind, message.clone())));
        }
        if self.read_closed || buf.remaining() == 0 {
            return Poll::Ready(Ok(()));
        }
        if let Some(response) = &mut self.response {
            let response = ready!(Pin::new(response).poll(cx)).map_err(h2_error)?;
            self.response = None;
            if response.status() != StatusCode::OK {
                return Poll::Ready(Err(invalid(format!(
                    "XHTTP HTTP/2 response status {}",
                    response.status()
                ))));
            }
            if response
                .headers()
                .get("content-encoding")
                .is_some_and(|value| !value.as_bytes().eq_ignore_ascii_case(b"identity"))
            {
                return Poll::Ready(Err(io::Error::new(
                    io::ErrorKind::Unsupported,
                    "compressed XHTTP response bodies are not implemented",
                )));
            }
            self.recv = Some(response.into_body());
        }
        for _ in 0..64 {
            let recv = self
                .recv
                .as_mut()
                .expect("response installs receive stream");
            if !self.received.is_empty() {
                let length = self.received.len().min(buf.remaining());
                buf.put_slice(&self.received[..length]);
                self.received.advance(length);
                recv.flow_control()
                    .release_capacity(length)
                    .map_err(h2_error)?;
                return Poll::Ready(Ok(()));
            }
            if !self.data_ended {
                match ready!(recv.poll_data(cx)) {
                    Some(Ok(bytes)) => {
                        self.received = bytes;
                        continue;
                    }
                    Some(Err(error)) => return Poll::Ready(Err(h2_error(error))),
                    None => self.data_ended = true,
                }
            }
            // XHTTP is ordinary HTTP: trailers may exist but carry no mandatory
            // gRPC status. Polling them still surfaces an H2 failure.
            let _ = ready!(recv.poll_trailers(cx)).map_err(h2_error)?;
            self.read_closed = true;
            return Poll::Ready(Ok(()));
        }
        cx.waker().wake_by_ref();
        Poll::Pending
    }

    fn poll_capacity(&mut self, cx: &mut Context<'_>, desired: usize) -> Poll<io::Result<usize>> {
        if self.write_closed {
            return Poll::Ready(Err(io::Error::new(
                io::ErrorKind::BrokenPipe,
                "XHTTP HTTP/2 write side closed",
            )));
        }
        if let Poll::Ready(reset) = self.send.poll_reset(cx) {
            return Poll::Ready(Err(match reset {
                Ok(reason) => h2_error(reason.into()),
                Err(error) => h2_error(error),
            }));
        }
        if desired == 0 {
            return Poll::Ready(Ok(0));
        }
        self.send.reserve_capacity(desired.min(WRITE_CHUNK));
        if self.send.capacity() > 0 {
            return Poll::Ready(Ok(self.send.capacity().min(desired).min(WRITE_CHUNK)));
        }
        match ready!(self.send.poll_capacity(cx)) {
            Some(Ok(capacity)) if capacity > 0 => {
                Poll::Ready(Ok(capacity.min(desired).min(WRITE_CHUNK)))
            }
            Some(Ok(_)) => {
                cx.waker().wake_by_ref();
                Poll::Pending
            }
            Some(Err(error)) => Poll::Ready(Err(h2_error(error))),
            None => Poll::Ready(Err(io::Error::new(
                io::ErrorKind::BrokenPipe,
                "XHTTP HTTP/2 stream closed",
            ))),
        }
    }
}

impl AsyncRead for Tunnel {
    fn poll_read(
        mut self: Pin<&mut Self>,
        cx: &mut Context<'_>,
        buf: &mut ReadBuf<'_>,
    ) -> Poll<io::Result<()>> {
        let result = self.poll_read_inner(cx, buf);
        if let Poll::Ready(Err(error)) = &result {
            self.terminal_error = Some((error.kind(), error.to_string()));
            self.send.send_reset(h2::Reason::CANCEL);
        }
        result
    }
}

impl AsyncWrite for Tunnel {
    fn poll_write(
        mut self: Pin<&mut Self>,
        cx: &mut Context<'_>,
        bytes: &[u8],
    ) -> Poll<io::Result<usize>> {
        let length = ready!(self.poll_capacity(cx, bytes.len()))?;
        if length > 0 {
            self.send
                .send_data(Bytes::copy_from_slice(&bytes[..length]), false)
                .map_err(h2_error)?;
        }
        Poll::Ready(Ok(length))
    }
    fn poll_write_vectored(
        mut self: Pin<&mut Self>,
        cx: &mut Context<'_>,
        buffers: &[io::IoSlice<'_>],
    ) -> Poll<io::Result<usize>> {
        let desired = buffers
            .iter()
            .fold(0usize, |size, buffer| size.saturating_add(buffer.len()))
            .min(WRITE_CHUNK);
        let capacity = ready!(self.poll_capacity(cx, desired))?;
        let mut bytes = BytesMut::with_capacity(capacity);
        for buffer in buffers {
            let length = buffer.len().min(capacity - bytes.len());
            bytes.extend_from_slice(&buffer[..length]);
            if bytes.len() == capacity {
                break;
            }
        }
        let length = bytes.len();
        if length > 0 {
            self.send
                .send_data(bytes.freeze(), false)
                .map_err(h2_error)?;
        }
        Poll::Ready(Ok(length))
    }
    fn is_write_vectored(&self) -> bool {
        true
    }
    fn poll_flush(mut self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<io::Result<()>> {
        if self.write_closed {
            return Poll::Ready(Ok(()));
        }
        self.poll_capacity(cx, 0).map_ok(|_| ())
    }
    fn poll_shutdown(mut self: Pin<&mut Self>, _cx: &mut Context<'_>) -> Poll<io::Result<()>> {
        if self.write_closed {
            return Poll::Ready(Ok(()));
        }
        self.send.send_data(Bytes::new(), true).map_err(h2_error)?;
        self.write_closed = true;
        Poll::Ready(Ok(()))
    }
}

impl Drop for Tunnel {
    fn drop(&mut self) {
        if !self.write_closed || (self.role == Role::Client && !self.read_closed) {
            self.send.send_reset(h2::Reason::CANCEL);
        }
    }
}

