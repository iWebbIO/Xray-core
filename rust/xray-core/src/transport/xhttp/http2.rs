//! XHTTP stream-one over HTTP/2, isolated from the HTTP/1 transport owner.
//!
//! Source: transport/internet/splithttp/{client,config,hub,dialer}.go. A single
//! request body is the uplink and its response body is the downlink. Despite
//! application/grpc camouflage, DATA is raw application bytes: no gRPC message
//! envelopes or grpc-status trailers exist. Both directions may half-close.
//!
//! Integration requires `pub mod http2;` in the parent xhttp module. Existing
//! Config request/response/metadata/padding helpers are reused, translating only
//! their HTTP framing. The client requires explicit stream-one; packet-up,
//! stream-up, auto-mode selection, Xmux policy, and HTTP/3 remain outer work.
//! Supplied TLS/REALITY streams must have actually negotiated h2. This module
//! cannot inspect TLS metadata once it has been erased into BoxStream.

use std::{
    collections::HashSet,
    future::Future,
    io,
    pin::Pin,
    sync::Arc,
    task::{Context, Poll, ready},
    time::Duration,
};

use bytes::{Buf, Bytes, BytesMut};
use h2::{RecvStream, SendStream, client::ResponseFuture};
use http::{
    HeaderMap, HeaderName, HeaderValue, Method, Request, Response, StatusCode, Uri, Version,
};
use tokio::{
    io::{AsyncRead, AsyncWrite, ReadBuf},
    sync::mpsc,
    task::JoinHandle,
};

