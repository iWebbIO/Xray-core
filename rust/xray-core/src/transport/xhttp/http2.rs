    async fn bounded<T>(future: impl Future<Output = T>) -> T {
        tokio::time::timeout(Duration::from_secs(8), future)
            .await
            .expect("XHTTP H2 test timed out")
    }

    async fn pair_with(client_config: Config, server_config: Config) -> (Client, Server) {
        let (a, b) = tokio::io::duplex(4096);
        let (client, server) = tokio::join!(
            Client::handshake(Box::new(a), client_config),
            Server::handshake(Box::new(b), server_config),
        );
        (client.unwrap(), server.unwrap())
    }

    async fn pair() -> (Client, Server) {
        pair_with(config(), config()).await
    }

    struct RawPeer {
        _client: Client,
        tunnel: Tunnel,
        request: Request<RecvStream>,
        response: h2::server::SendResponse<Bytes>,
        _driver: Driver,
    }

    async fn raw_peer(window: u32) -> RawPeer {
        let (a, b) = tokio::io::duplex(4096);
        let (tx, rx) = tokio::sync::oneshot::channel();
        let driver = Driver(tokio::spawn(async move {
            let mut builder = h2::server::Builder::new();
            builder.initial_window_size(window);
            let mut connection = builder
                .handshake::<_, Bytes>(Box::new(b) as BoxStream)
                .await
                .unwrap();
            assert!(tx.send(connection.accept().await.unwrap().unwrap()).is_ok());
            while connection.accept().await.is_some() {}
        }));
        let client = Client::handshake(Box::new(a), config()).await.unwrap();
        let tunnel = client.open().await.unwrap();
        let (request, response) = rx.await.unwrap();
        RawPeer {
            _client: client,
            tunnel,
            request,
            response,
            _driver: driver,
        }
    }

    fn response_headers() -> Response<()> {
        Response::builder()
            .status(200)
            .header("content-type", "text/event-stream")
            .body(())
            .unwrap()
    }

